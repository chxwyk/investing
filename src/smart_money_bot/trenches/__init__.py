"""Terminal-style public/on-chain intelligence for Pump.fun trenches and Trending.

This package is the v2.43 research brain: Pump.fun lifecycle and bonding
progress, multi-timeframe momentum, buyer independence, fresh-wallet and bundle
clustering, dev intelligence, holder concentration trends, explicit risk
dimensions, our own PUBLIC_TRENDING_MODEL, source consensus, and the manual
benchmark tool.

Like :mod:`smart_money_bot.lab`, :mod:`smart_money_bot.trending` and everything
else that decides things here, it is pure logic: no network client, no database
handle, no Discord object, no wallet, no signer.  Evidence in, graded states and
scores out.  That is what makes every rule testable without a provider and what
structurally guarantees this package cannot spend money or touch a private API.

**Nothing in this package can execute a real trade, and nothing in it reads any
authenticated third-party surface.**
"""

