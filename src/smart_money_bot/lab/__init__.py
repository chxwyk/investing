"""The autonomous PAPER-trading research laboratory.

This package is the trading *brain*.  It is deliberately independent of Discord,
of any provider client, and of any deployment: it takes evidence in and produces
decisions, positions and reports out.  That separation is what makes the same
engine reusable for a different instance later without rewriting strategy code —
and it is why the package contains no network client, no wallet, and no signing
path of any kind.

**This release is PAPER only.**  Nothing in this package can move real funds.
"""

