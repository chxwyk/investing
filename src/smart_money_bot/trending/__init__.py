"""The Trending-first alpha engine.

This package is the bot's new *primary* research universe: what is trending
right now, why, who is talking about it, and whether any of it is still
tradeable.  Legacy graduated discovery is not deleted — it stays as a secondary
lane (section 39) — but it is no longer the main hunting ground.

Like :mod:`smart_money_bot.lab`, everything in here is pure logic.  No network
client, no database handle, no Discord object, no wallet and no signing path of
any kind.  Evidence goes in; states, scores and reasons come out.  That is what
makes the whole thing testable without a provider and what guarantees,
structurally, that this package cannot spend money.

**Nothing in this package can execute a real trade.**
"""

